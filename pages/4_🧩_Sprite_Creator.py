"""Sprite Creator page for Streamlit app."""

from __future__ import annotations

from dataclasses import dataclass

import streamlit as st
from PIL import Image

from scrapper.sprite_creator import (
    ICON_COPIES,
    ICON_SIZE,
    SHEET_COPIES,
    SIDE_FACINGS,
    SPRITE_SIZE,
    SpriteCreatorError,
    SpritePackage,
    build_sprite_package,
    load_sprite_image,
    resolve_sprite_number,
    to_png_bytes,
)

_SLOTS = (
    ("front", "Front sprite", "f", "Facing the viewer"),
    ("back", "Back sprite", "b", "Facing away from the viewer"),
    ("side", "Side sprite", "s", "Facing left or right"),
)


@dataclass(frozen=True)
class UploadedSprite:
    """An uploaded sprite file with its original name."""

    name: str
    data: bytes


def main() -> None:
    st.set_page_config(
        page_title="Sprite Creator",
        page_icon="🧩",
        layout="wide",
    )

    st.title("🧩 Sprite Creator")
    st.caption(
        "Turn a front, back and side sprite into a ready-to-use sprite set: "
        f"{SPRITE_SIZE}×{SPRITE_SIZE} portraits, {ICON_SIZE}×{ICON_SIZE} icons "
        "and a 4-row character spritesheet."
    )

    uploads, side_facing = render_inputs()

    if st.button("Build Sprite Set", type="primary", disabled=len(uploads) < len(_SLOTS)):
        run_build(uploads, side_facing)

    render_result()


def render_inputs() -> tuple[dict[str, UploadedSprite], str]:
    with st.sidebar:
        st.header("Settings")

        st.subheader("Side Sprite")
        side_facing = st.radio(
            "The uploaded side sprite faces",
            options=list(SIDE_FACINGS),
            format_func=str.capitalize,
            index=0,
            help="The opposite direction is generated by mirroring the sprite.",
        )

        st.divider()
        st.subheader("Outputs")
        st.caption(
            f"Front / back sprite: {SPRITE_SIZE}×{SPRITE_SIZE} px\n\n"
            f"Icons: {ICON_COPIES} × {ICON_SIZE}×{ICON_SIZE} px\n\n"
            f"Spritesheet: {SHEET_COPIES} × {ICON_SIZE}×{ICON_SIZE} px per row, "
            "rows front → left → right → back"
        )

    st.subheader("Sprite Source")
    st.caption(
        "Upload three PNG files that share one number, e.g. "
        "`500f.png`, `500b.png` and `500s.png`."
    )

    uploads: dict[str, UploadedSprite] = {}
    columns = st.columns(len(_SLOTS))

    for column, (role, label, suffix, description) in zip(columns, _SLOTS):
        with column:
            uploaded = st.file_uploader(
                f"{label} (`<number>{suffix}.png`)",
                type=["png"],
                key=f"sprite_{role}",
                help=description,
            )
            if uploaded is not None:
                uploads[role] = UploadedSprite(
                    name=uploaded.name, data=uploaded.getvalue()
                )

    return uploads, side_facing


def run_build(uploads: dict[str, UploadedSprite], side_facing: str) -> None:
    try:
        with st.spinner("Building sprite set..."):
            package = build_sprite_package(
                number=resolve_sprite_number(
                    {role: upload.name for role, upload in uploads.items()}
                ),
                side_facing=side_facing,
                **{
                    role: load_sprite_image(upload.data, role)
                    for role, upload in uploads.items()
                },
            )
    except SpriteCreatorError as exc:
        st.session_state["sprite_error"] = str(exc)
        st.session_state["sprite_result"] = None
        return

    st.session_state["sprite_result"] = package
    st.session_state["sprite_error"] = None


def render_result() -> None:
    error = st.session_state.get("sprite_error")
    result: SpritePackage | None = st.session_state.get("sprite_result")

    if error:
        st.error(f"Could not build the sprite set: {error}")
        return

    if result is None:
        return

    st.divider()
    st.subheader(f"Sprite Set {result.number}")
    render_metrics(result)

    render_portraits(result)
    render_icons(result)
    render_spritesheet(result)


def render_portraits(result: SpritePackage) -> None:
    st.markdown("**Front Sprite** and **Back Sprite**")
    col1, col2 = st.columns(2)

    with col1:
        render_downloadable(
            result.front_sprite,
            caption=f"{SPRITE_SIZE}×{SPRITE_SIZE} px",
            file_name=f"{result.number}.png",
            key="front_sprite",
        )

    with col2:
        render_downloadable(
            result.back_sprite,
            caption=f"{SPRITE_SIZE}×{SPRITE_SIZE} px",
            file_name=f"{result.number}b.png",
            key="back_sprite",
        )


def render_icons(result: SpritePackage) -> None:
    st.divider()
    st.markdown("**Icons**")
    render_downloadable(
        result.icons,
        caption=(
            f"{result.icons.width}×{result.icons.height} px · "
            f"{ICON_COPIES} × {ICON_SIZE}×{ICON_SIZE} px"
        ),
        file_name=f"icon{result.number}.png",
        key="icons",
    )


def render_spritesheet(result: SpritePackage) -> None:
    st.divider()
    st.markdown("**Character Spritesheet**")
    st.caption("Rows top to bottom: front · left · right · back")
    render_downloadable(
        result.spritesheet,
        caption=(
            f"{result.spritesheet.width}×{result.spritesheet.height} px · "
            f"{SHEET_COPIES} copies of {ICON_SIZE}×{ICON_SIZE} px per row"
        ),
        file_name=f"{result.number}_sheet.png",
        key="spritesheet",
    )


def render_downloadable(
    image: Image.Image, caption: str, file_name: str, key: str
) -> None:
    st.image(image, caption=caption)
    st.download_button(
        f"Download `{file_name}`",
        data=to_png_bytes(image),
        file_name=file_name,
        mime="image/png",
        key=f"download_{key}",
    )


def render_metrics(result: SpritePackage) -> None:
    col1, col2, col3, col4 = st.columns(4)
    col1.metric("Sprite number", result.number)
    col2.metric("Side sprite faces", result.side_facing.capitalize())
    col3.metric("Portraits", f"{SPRITE_SIZE}×{SPRITE_SIZE}")
    col4.metric("Sheet size", f"{result.spritesheet.width}×{result.spritesheet.height}")


if __name__ == "__main__":
    main()
